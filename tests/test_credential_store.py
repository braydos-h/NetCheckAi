def test_confirm_credential_is_only_path_to_confirmed(monkeypatch, tmp_path):
    monkeypatch.delenv("AI_NMAP_VAULT_KEY", raising=False)
    store = CredentialStore(tmp_path)
    store.add(_rec(username="admin", target_host="10.0.0.50"))
    assert store.all_credentials()[0].confirmed is False

    # confirm without validated=True is refused by the gate -- flips nothing
    assert store.confirm_credential(username="admin", target_host="10.0.0.50") is False
    assert store.all_credentials()[0].confirmed is False
    # confirm with validated=True flips it
    assert store.confirm_credential(username="admin", target_host="10.0.0.50", validated=True) is True
    assert store.all_credentials()[0].confirmed is True
    # re-confirm of already-confirmed returns False (no new confirmation)
    assert store.confirm_credential(username="admin", target_host="10.0.0.50", validated=True) is False
    # confirm of a non-existent cred returns False
    assert store.confirm_credential(username="nobody", target_host="10.0.0.50", validated=True) is False
    # confirm persisted to disk (encrypted + HMAC-signed) and reloads confirmed
    s2 = CredentialStore(tmp_path)
    assert s2.all_credentials()[0].confirmed is True


def test_confirm_credential_filtered_by_type(monkeypatch, tmp_path):
    monkeypatch.delenv("AI_NMAP_VAULT_KEY", raising=False)
    store = CredentialStore(tmp_path)
    store.add(_rec(username="svc", password=_CLEARTEXT, ctype="password"))
    store.add(_rec(username="svc", password=_NTLM, ctype="hash"))
    # confirm only the hash, not the password
    assert (
        store.confirm_credential(username="svc", target_host="10.0.0.50", credential_type="hash", validated=True)
        is True
    )
    pw, h = sorted(store.all_credentials(), key=lambda r: r.credential_type)
    assert pw.credential_type == "hash" and pw.confirmed is True
    assert h.credential_type == "password" and h.confirmed is False


