@pytest.mark.asyncio
async def test_list_workspace_shows_credentials_via_link_alias_lab(monkeypatch, tmp_path):
    """LAB BUILD: the credentials/ subtree is shown (nothing is hidden). A symlink
    alias is NOT followed (os.walk followlinks=False), so only the real credentials/
    subtree is enumerated -- but it IS shown (the lab build does not hide it)."""
    import os
    import subprocess

    monkeypatch.delenv("AI_NMAP_VAULT_KEY", raising=False)
    mcp = _make_server(tmp_path)
    await mcp.call_tool("cred_store_add", {"target_ip": "10.0.0.50", "username": "admin", "password": _CLEARTEXT})
    cred_dir = tmp_path / "credentials"
    alias = tmp_path / "data"
    # try a real symlink first (POSIX always; Windows needs dev-mode/privilege)
    created = False
    try:
        os.symlink(cred_dir, alias, target_is_directory=True)
        created = True
    except (OSError, NotImplementedError):
        created = False
    # Windows junction via mklink /J needs no privilege
    if not created and os.name == "nt":
        try:
            r = subprocess.run(
                ["cmd", "/c", "mklink", "/J", str(alias), str(cred_dir)],
                capture_output=True,
                timeout=10,
            )
            created = r.returncode == 0
        except Exception:
            created = False
    if not created:
        pytest.skip("link/junction creation unavailable in this environment")
    listed = _text(await mcp.call_tool("list_workspace", {}))
    low = listed.lower()
    # the real credentials/ subtree is shown (the lab build does not hide it)
    assert "credentials" in low
    assert ".vault_key" not in listed  # keyfile names are never listed
    assert "credentials.jsonl" in listed
