# ── 4. HMAC integrity + validated gate (Tier 0 item 0.3, Unit E) ─────────────
#
# ``confirmed=True`` is the trust gate for credential reuse. Two defenses pin it:
# (1) ``confirm_credential`` refuses without ``validated=True``, so a careless or
#     harvest-time call cannot promote an unvalidated credential; (2) the
#     ``confirmed`` flag is HMAC-signed at rest, so a hand-edited file, a file
#     copied from another workspace, or anything written under plaintext fallback
#     cannot carry a forged ``confirmed=True`` into memory -- it is downgraded to
#     False on load and logged.


def test_confirm_refused_without_validated_flag(monkeypatch, tmp_path):
    monkeypatch.delenv("AI_NMAP_VAULT_KEY", raising=False)
    store = CredentialStore(tmp_path)
    store.add(_rec(username="admin", target_host="10.0.0.50"))
    # bare confirm flips nothing and persists nothing
    assert store.confirm_credential(username="admin", target_host="10.0.0.50") is False
    assert store.all_credentials()[0].confirmed is False
    disk = (tmp_path / "credentials.jsonl").read_text(encoding="utf-8")
    assert json.loads(disk.strip().splitlines()[-1])["confirmed"] is False


def test_hmac_confirmed_survives_reload_same_key(monkeypatch, tmp_path):
    """A signed confirmed=True reloads confirmed under the same vault key."""
    key = Fernet.generate_key().decode()
    monkeypatch.setenv("AI_NMAP_VAULT_KEY", key)
    store = CredentialStore(tmp_path)
    store.add(_rec(username="admin", target_host="10.0.0.50"))
    assert store.confirm_credential(username="admin", target_host="10.0.0.50", validated=True) is True
    line = json.loads((tmp_path / "credentials.jsonl").read_text(encoding="utf-8").strip().splitlines()[-1])
    assert "sig" in line and line["sig"]  # on-disk record carries an HMAC
    s2 = CredentialStore(tmp_path)
    assert s2.all_credentials()[0].confirmed is True  # sig verifies -> survives


def test_hmac_tampered_confirmed_downgraded(monkeypatch, tmp_path):
    """A hand-edited confirmed=True with no HMAC is downgraded on load -- a forged
    confirmed flag is never trusted."""
    key = Fernet.generate_key().decode()
    monkeypatch.setenv("AI_NMAP_VAULT_KEY", key)
    store = CredentialStore(tmp_path)
    store.add(_rec(username="admin", target_host="10.0.0.50"))
    store_path = tmp_path / "credentials.jsonl"
    rec_line = json.loads(store_path.read_text(encoding="utf-8").strip().splitlines()[-1])
    rec_line["confirmed"] = True
    rec_line.pop("sig", None)  # strip the signature -> unauthenticated
    store_path.write_text(json.dumps(rec_line) + "\n", encoding="utf-8")
    s2 = CredentialStore(tmp_path)
    assert s2.all_credentials()[0].confirmed is False  # downgraded, not trusted


def test_hmac_flipped_confirmed_breaks_signature(monkeypatch, tmp_path):
    """Flipping confirmed=True on a signed record (leaving the stale sig) makes the
    signature not verify under the key -> downgraded. Tamper-evidence holds even
    when the attacker knows to keep a sig field."""
    key = Fernet.generate_key().decode()
    monkeypatch.setenv("AI_NMAP_VAULT_KEY", key)
    store = CredentialStore(tmp_path)
    store.add(_rec(username="admin", target_host="10.0.0.50"))
    store_path = tmp_path / "credentials.jsonl"
    rec_line = json.loads(store_path.read_text(encoding="utf-8").strip().splitlines()[-1])
    rec_line["confirmed"] = True  # flip the flag, KEEP the (now-stale) sig
    store_path.write_text(json.dumps(rec_line) + "\n", encoding="utf-8")
    s2 = CredentialStore(tmp_path)
    assert s2.all_credentials()[0].confirmed is False  # sig no longer matches


def test_hmac_foreign_workspace_confirmed_downgraded(monkeypatch, tmp_path):
    """A confirmed=True signed under a different vault key is downgraded when read
    under this workspace's key (the file was copied in from elsewhere)."""
    key_a = Fernet.generate_key().decode()
    monkeypatch.setenv("AI_NMAP_VAULT_KEY", key_a)
    store_a = CredentialStore(tmp_path)
    store_a.add(_rec(username="admin", target_host="10.0.0.50"))
    assert store_a.confirm_credential(username="admin", target_host="10.0.0.50", validated=True) is True
    # read the same on-disk file under a DIFFERENT key -> sig does not verify
    monkeypatch.setenv("AI_NMAP_VAULT_KEY", Fernet.generate_key().decode())
    store_b = CredentialStore(tmp_path)
    assert store_b.all_credentials()[0].confirmed is False


def test_plaintext_fallback_confirmed_never_trusted_from_disk(monkeypatch, tmp_path):
    """In plaintext-fallback mode no HMAC can be produced, so a confirmed=True on
    disk is never trusted and is downgraded on reload -- only a SIGNED confirmed
    survives. (The in-memory confirm still works; the gate is the reload.)"""
    _Vault._plaintext_warned = False
    real = sys.modules.get("cryptography.fernet")
    sys.modules["cryptography.fernet"] = None  # force ImportError inside _Vault
    try:
        store = CredentialStore(tmp_path)
        assert store.encryption_enabled is False
        store.add(_rec(username="admin", target_host="10.0.0.50"))
        # the validated gate still flips the in-memory flag
        assert store.confirm_credential(username="admin", target_host="10.0.0.50", validated=True) is True
        assert store.all_credentials()[0].confirmed is True
        # but no sig could be written, so a reload must not trust confirmed=True
        s2 = CredentialStore(tmp_path)
        assert s2.all_credentials()[0].confirmed is False
    finally:
        if real is None:
            sys.modules.pop("cryptography.fernet", None)
        else:
            sys.modules["cryptography.fernet"] = real


# ── 5. Workspace read/list denylist for credential artifacts (Unit E) ────────


def _read_audit(workspace: Path) -> list[dict[str, Any]]:
    audit = workspace / "exploit_audit.jsonl"
    if not audit.exists():
        return []
    return [json.loads(line) for line in audit.read_text(encoding="utf-8").splitlines() if line.strip()]


